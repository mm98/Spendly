/* What a file actually is, read from its own first bytes -- never decided from what the caller
   said (`file.mimetype` or the filename), because both are the caller's to write. A browser
   fills the mimetype in from the operating system's own extension mapping, so a renamed file
   lies twice in the same breath, and a script posting to the API can say anything at all. The
   bytes cannot: a PDF starts "%PDF" whatever it is called.

   That matters in three places. The image branch hands sharp bytes it cannot decode if a PDF
   is mistaken for one, storing raw bytes with no thumbnail and no way to preview it. mupdf
   parses whatever is routed to it as a PDF -- expensive to run against a large file that isn't
   one. And the stored content type, served back on the /file route as a Content-Type header,
   has to be the bytes' own type rather than whatever was claimed.

   Signatures verified against files generated by this project's own sharp build rather than
   copied from memory. Note the widths: four bytes settles JPEG, PNG, PDF, GIF and TIFF, but
   RIFF at 0 is also WAV and AVI so WebP needs bytes 8-11 as well, and an AVIF/HEIC file opens
   with a *box length* that varies per file, with the brand at 4-11. A four-byte reader would
   call every one of those "unknown", which is why this one reads twelve.

   Deliberately not a security boundary. It says what a container claims to be, not whether it
   is safe: sharp and mupdf are still the things parsing untrusted bytes, and a valid PDF can
   still be a malicious one. It is here for correctness -- so the pipeline treats a file as
   what it is. A file picked or dropped in the app must be one of these (assertImageOrPdf); in
   the bulk import an unrecognised attachment is tried as a picture and refused when it is not. */

const ascii = text => [...text].map(c => c.charCodeAt(0))

/* Each entry is a list of (offset, bytes) pairs that all have to match. `kind` is the
   attachment kind the schema allows (migrations/001: 'pdf' or 'image', and nothing else). A
   format sharp cannot decode still files as an image, and processAttachment refuses it. */
const SIGNATURES = [
	{ type: 'application/pdf', kind: 'pdf', parts: [[0, ascii('%PDF')]] },
	{ type: 'image/jpeg', kind: 'image', parts: [[0, [0xff, 0xd8, 0xff]]] },
	{ type: 'image/png', kind: 'image', parts: [[0, [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]]] },
	{ type: 'image/gif', kind: 'image', parts: [[0, ascii('GIF8')]] },
	// RIFF....WEBP -- the four bytes between are the file length, which is why they are skipped.
	{ type: 'image/webp', kind: 'image', parts: [[0, ascii('RIFF')], [8, ascii('WEBP')]] },
	// ISO base media: a box length, then 'ftyp', then the brand that says which format it is.
	{ type: 'image/avif', kind: 'image', parts: [[4, ascii('ftyp')], [8, ascii('avif')]] },
	{ type: 'image/avif', kind: 'image', parts: [[4, ascii('ftyp')], [8, ascii('avis')]] },
	{ type: 'image/heic', kind: 'image', parts: [[4, ascii('ftyp')], [8, ascii('heic')]] },
	{ type: 'image/heic', kind: 'image', parts: [[4, ascii('ftyp')], [8, ascii('heix')]] },
	{ type: 'image/heif', kind: 'image', parts: [[4, ascii('ftyp')], [8, ascii('mif1')]] },
	{ type: 'image/tiff', kind: 'image', parts: [[0, [0x49, 0x49, 0x2a, 0x00]]] },
	{ type: 'image/tiff', kind: 'image', parts: [[0, [0x4d, 0x4d, 0x00, 0x2a]]] },
	{ type: 'image/bmp', kind: 'image', parts: [[0, ascii('BM')]] }
]

const matches = (buffer, parts) => parts.every(([at, bytes]) =>
	bytes.every((byte, i) => buffer[at + i] === byte))

/** The format a buffer's own bytes declare -- { type, kind } -- or null for anything not in
    the table above. Reads at most the first twelve bytes and copies nothing. */
export function detectFileType(buffer) {
	if (!buffer || buffer.length < 4) return null
	return SIGNATURES.find(signature => matches(buffer, signature.parts)) ?? null
}

/** The attachment kind to file a buffer under: what the bytes say, and only if they say
    nothing, what the caller claimed. Everything unrecognised is an image: sharp tries to read
    it, and processAttachment refuses it when it cannot. */
export function detectKind(buffer, declaredType, name) {
	const detected = detectFileType(buffer)
	if (detected) return detected.kind
	return declaredType === 'application/pdf' || /\.pdf$/i.test(name ?? '') ? 'pdf' : 'image'
}

/** Refuses an upload, with a sentence, when any of its files is not an image or a PDF by its
    own bytes -- before anything is stored, so a refused upload adds nothing. */
export function assertImageOrPdf(files) {
	const other = files.find(file => !detectFileType(file.buffer))
	if (other) throw Object.assign(new Error(`The file "${other.originalname}" is not an image or a PDF. Nothing was added.`), { status: 415 })
}
