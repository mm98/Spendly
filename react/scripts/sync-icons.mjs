import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/* The Tabler outline library a category's icon is picked from (Components c7), generated from
   @tabler/icons into src/components/tabler. Run: npm run icons:sync, or icons:check in CI. */

const here = path.dirname(fileURLToPath(import.meta.url))
const PACKAGE = path.join(here, '..', 'node_modules', '@tabler', 'icons')
const SOURCE = path.join(PACKAGE, 'icons', 'outline')
const META = path.join(PACKAGE, 'icons.json')
const TARGET = path.join(here, '..', 'src', 'components', 'tabler')

// the 24 the picker shows before anything is typed (c7), in the design's order; they load as one part
const COMMON = [
	'tag', 'home', 'shopping-cart', 'basket', 'tools-kitchen-2', 'car', 'bike', 'gas-station', 'bus', 'plane', 'paw', 'plant',
	'baby-carriage', 'shirt', 'first-aid-kit', 'pill', 'school', 'device-laptop', 'device-mobile', 'gift', 'armchair', 'lamp', 'tool', 'wallet'
]

const BOUNDS = 'M0 0h24v24H0z'
// the generated files hold their data in template literals, one record per line
const SAFE = /^[^`\\\n\r\t$]*$/

// a part per first letter, digits together, so a mark finds its part from the name alone
const partOf = name => (COMMON.includes(name) ? 'common' : /^[0-9]/.test(name) ? '0' : name[0])

// Tabler's tags as single words, without the words the name already holds
const keywords = (name, tags) => {
	const own = new Set(name.split('-'))
	const words = []
	for (const tag of tags ?? []) {
		for (const word of String(tag).toLowerCase().split(/[^a-z0-9]+/)) {
			if (!word || /^[0-9]+$/.test(word) || own.has(word) || words.includes(word)) continue
			words.push(word)
		}
	}
	return words.join(' ')
}

/* Each icon's paths as Tabler draws them, one by one, since one merged path draws its crossings
   differently. A path's settings besides its line are carried as a mark Icon.jsx reads; a setting
   with no mark stops the sync, so a drawing never changes unnoticed. */
const MARKS = { '': '', 'fill=currentColor': '*', 'fill=currentColor stroke=none': '#', 'opacity=.5': '~' }

const collect = () => {
	const icons = {}
	for (const file of fs.readdirSync(SOURCE).filter(f => f.endsWith('.svg')).sort()) {
		const svg = fs.readFileSync(path.join(SOURCE, file), 'utf8')
		for (const [, tag] of svg.matchAll(/<([a-z]+)\b/g)) if (tag !== 'svg' && tag !== 'path') throw new Error(`${file} draws a ${tag}`)
		const paths = []
		for (const [, attrs] of svg.matchAll(/<path\b([^>]*)>/g)) {
			const d = /\bd="([^"]*)"/.exec(attrs)?.[1].trim()
			if (!d || d === BOUNDS) continue
			const style = [...attrs.matchAll(/([a-z-]+)="([^"]*)"/g)]
				.filter(([, key, value]) => key !== 'd' && !(key === 'fill' && value === 'none'))
				.map(([, key, value]) => `${key}=${value}`).sort().join(' ')
			if (!(style in MARKS) || !d.startsWith('M')) throw new Error(`${file} draws a path this sync does not carry: ${style || d}`)
			paths.push(MARKS[style] + d)
		}
		if (paths.length) icons[file.slice(0, -4)] = paths
	}
	return icons
}

const literal = lines => {
	for (const line of lines) if (!SAFE.test(line.replace(/\t/g, ''))) throw new Error(`cannot be written as a template literal: ${line}`)
	return `\`${lines.join('\n')}\`.split('\\n')`
}

const HEAD = '/* Generated by scripts/sync-icons.mjs from @tabler/icons. Do not edit. */\n\n'

const build = () => {
	const icons = collect()
	const names = Object.keys(icons)
	for (const name of COMMON) if (!icons[name]) throw new Error(`${name} is not in @tabler/icons`)
	const meta = JSON.parse(fs.readFileSync(META, 'utf8'))

	const files = new Map()
	// one line per icon: name, category, search words
	files.set('index.js', `${HEAD}export default ${literal(names.map(n => [n, (meta[n]?.category ?? '').toLowerCase(), keywords(n, meta[n]?.tags)].join('\t')))}\n`)

	const parts = new Map()
	for (const name of names) {
		const key = partOf(name)
		if (!parts.has(key)) parts.set(key, [])
		parts.get(key).push(`${name}\t${icons[name].join('\t')}`)
	}
	parts.get('common').sort((a, b) => COMMON.indexOf(a.split('\t')[0]) - COMMON.indexOf(b.split('\t')[0]))
	const keys = [...parts.keys()].sort()
	// one line per icon: name, then each of its paths
	for (const key of keys) files.set(`${key}.js`, `${HEAD}export default ${literal(parts.get(key))}\n`)

	files.set('parts.js', `${HEAD}export const COMMON = ${JSON.stringify(COMMON)}\n\n`
		+ `export const PARTS = {\n${keys.map(k => `\t${/^[a-z]+$/.test(k) ? k : `'${k}'`}: () => import('./${k}.js')`).join(',\n')}\n}\n`)
	return { files, count: names.length, parts: keys.length }
}

// the interface's own icons keep the names they hold; only their drawings follow the package
const REGISTER = path.join(here, '..', 'src', 'components', 'icons.js')
const registerText = icons => fs.readFileSync(REGISTER, 'utf8').replace(/^\t"([^"]+)": \[.*\](,?)$/gm, (_, name, comma) => {
	if (!icons[name]) throw new Error(`${name} is in icons.js but not in @tabler/icons`)
	if (icons[name].some(d => /['\\]/.test(d))) throw new Error(`${name} cannot be written as a string`)
	return `\t"${name}": [${icons[name].map(d => `'${d}'`).join(', ')}]${comma}`
})

const library = collect()
// an icon the server gives a category by name, as the demo data does, has to be one the library draws
const API = path.join(here, '..', '..', 'api', 'src')
for (const file of fs.readdirSync(API, { recursive: true }).filter(f => f.endsWith('.js'))) {
	for (const [, name] of fs.readFileSync(path.join(API, file), 'utf8').matchAll(/\bicon: '([^']*)'/g)) {
		if (!library[name]) throw new Error(`api/src/${file} names the icon "${name}", which @tabler/icons does not have`)
	}
}

const built = build()
built.files.set('../icons.js', registerText(library))
const current = new Map()
if (fs.existsSync(TARGET)) for (const name of fs.readdirSync(TARGET)) current.set(name, fs.readFileSync(path.join(TARGET, name), 'utf8'))
current.set('../icons.js', fs.readFileSync(REGISTER, 'utf8'))
const stale = [...current.keys()].filter(name => !built.files.has(name))
const changed = [...built.files].filter(([name, text]) => current.get(name) !== text).map(([name]) => name)

if (process.argv.includes('--check')) {
	if (!stale.length && !changed.length) {
		console.log(`src/components/tabler and icons.js match @tabler/icons (${built.count} icons in ${built.parts} parts)`)
		process.exit(0)
	}
	console.error('The icon files are out of date. Run: npm run icons:sync')
	for (const name of [...changed, ...stale]) console.error(`  ${name}`)
	process.exit(1)
}

fs.mkdirSync(TARGET, { recursive: true })
for (const name of stale) fs.unlinkSync(path.join(TARGET, name))
for (const [name, text] of built.files) fs.writeFileSync(path.join(TARGET, name), text)
const bytes = [...built.files.values()].reduce((sum, text) => sum + Buffer.byteLength(text), 0)
console.log(`src/components/tabler written: ${built.count} icons in ${built.parts} parts, ${(bytes / 1024).toFixed(0)} kB`)
