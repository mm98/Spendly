import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/* The whole Tabler outline set, flattened to one path string per icon.

   The app's own 39 glyphs live in src/components/Icon.jsx and are the ones the interface
   draws: a chevron, a receipt, a trash can. This file is the *catalogue* the category picker
   offers, which is a different job -- 5,130 icons nobody's interface uses more than a handful
   of. It is generated rather than written, the same way src/styles/spendly.css is, so it
   cannot drift from the package it came from.

   Two things are dropped on the way through:

   - Every Tabler icon opens with `<path stroke="none" d="M0 0h24v24H0z" fill="none" />`, a
     transparent 24x24 box that exists to fix the bounds. Stroked like the rest of the icon it
     would draw a square around every glyph.
   - A handful of outline icons carry a filled path as well. Everything here is rendered with
     one stroke and no fill, so those paths are left out and the icon is listed without them --
     the alternative is a per-path fill attribute in every record, for about 1% of the set.

   The rest are joined into a single `d`. They are all subpaths of one stroke with the same
   width, cap and join, so `M… M… M…` draws exactly what the separate elements did -- which is
   the form the 39 built-in glyphs were already in.

   Run: npm run icons:sync    (and icons:check, which fails if the file is out of date) */

const here = path.dirname(fileURLToPath(import.meta.url))
const SOURCE = path.join(here, '..', 'node_modules', '@tabler', 'icons', 'icons', 'outline')
const TARGET = path.join(here, '..', 'src', 'api', 'tabler.js')

const BOUNDS = 'M0 0h24v24H0z'

const build = () => {
	const files = fs.readdirSync(SOURCE).filter(f => f.endsWith('.svg')).sort()
	const icons = {}
	let dropped = 0

	for (const file of files) {
		const svg = fs.readFileSync(path.join(SOURCE, file), 'utf8')
		const paths = [...svg.matchAll(/<path\b([^>]*)>/g)]
			.map(m => m[1])
			.filter(attrs => {
				const d = /\bd="([^"]*)"/.exec(attrs)?.[1] ?? ''
				if (!d || d === BOUNDS) return false
				const fill = /\bfill="([^"]*)"/.exec(attrs)?.[1]
				if (fill && fill !== 'none') { dropped++; return false }
				return true
			})
			.map(attrs => /\bd="([^"]*)"/.exec(attrs)[1].trim())

		if (paths.length) icons[file.slice(0, -4)] = paths.join(' ')
	}

	const body = Object.entries(icons)
		.map(([name, d]) => `\t${JSON.stringify(name)}: ${JSON.stringify(d)}`)
		.join(',\n')

	return {
		dropped,
		count: Object.keys(icons).length,
		text: `/* Generated by scripts/sync-icons.mjs from @tabler/icons. Do not edit.

   ${Object.keys(icons).length} outline icons, each flattened to one stroke path. This module is
   loaded on demand -- see components/Pickers.jsx -- so its weight is paid when the icon picker
   opens and never on first paint. What a record needs in order to be *drawn* is stored with the
   record, so nothing outside the picker imports this. */

export const TABLER = {
${body}
}

export default TABLER
`
	}
}

const built = build()
const check = process.argv.includes('--check')
const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : null

if (check) {
	if (current === built.text) {
		console.log(`tabler.js matches @tabler/icons (${built.count} icons)`)
		process.exit(0)
	}
	console.error('tabler.js is out of date. Run: npm run icons:sync')
	process.exit(1)
}

fs.writeFileSync(TARGET, built.text)
console.log(`tabler.js written: ${built.count} icons, ${built.dropped} filled paths dropped, `
	+ `${(Buffer.byteLength(built.text) / 1024).toFixed(0)} kB`)
